# Where each frozen figure's code and data come from, and under which
# license (bench v0, Task 5; owner's decision 2026-11-10: code and metadata
# in git, vendored data out). Writes bench/figures/SOURCES.md. Run where the
# package libraries are, before split.R (the manifest covers this file):
#   GLOSS_BENCH_OFFLINE=true bench/docker/run.sh Rscript bench/R/attribution.R
# Package versions and licenses are read from each figure's environment.

source("bench/R/harvest.R")

src <- jsonlite::fromJSON(file.path(bench_root, "frame", "sources.json"), simplifyVector = FALSE)
gallery_commit <- src$gallery$sha %||% stop("sources.json has no gallery sha")
ids <- sort(list.dirs(figures_root, full.names = FALSE, recursive = FALSE))

rows <- lapply(ids, function(id) {
  meta <- jsonlite::fromJSON(file.path(figures_root, id, "meta.json"), simplifyVector = FALSE)
  if (identical(meta$kind, "gallery")) {
    source <- sprintf("R Graph Gallery `%s` @ `%s`", meta$psu, substr(gallery_commit, 1, 7))
    version <- ""
    license <- "MIT (LICENSE-R-graph-gallery.txt)"
  } else if (identical(meta$kind, "book")) {
    # a chapter of the ggtree book (bench v1): its online version is CC BY-NC-SA 4.0
    source <- sprintf("Yu G., *Data Integration, Manipulation and Visualization of Phylogenetic Trees* (treedata-book), `%s` @ `%s`",
                      meta$psu, substr(sources$treebook$sha, 1, 7))
    version <- ""
    license <- "CC BY-NC-SA 4.0 (the book's online version, index.Rmd)"
  } else {
    pkg <- sub("::.*$", "", meta$psu)
    what <- switch(meta$kind, examples = "examples", topic = paste0("help `", sub("^.*::", "", meta$psu), "`"),
                   vignette = paste0("vignette `", meta$vignette, "`"), meta$kind)
    source <- sprintf("%s, %s", pkg, what)
    d <- tryCatch(utils::packageDescription(pkg, lib.loc = bench_libpaths(figure_env(meta)), fields = c("Version", "License")),
                  error = function(e) NULL, warning = function(w) NULL)
    version <- if (is.list(d)) d$Version else NA
    license <- if (is.list(d)) gsub("\\s+", " ", d$License) else NA
  }
  # only URLs actually vendored into data/ (a failed fetch leaves the URL in the code, file null)
  urls <- vapply(meta$rewrites, function(r) if (isTRUE(r$ok) && length(r$file)) r$url else "", "")
  data.frame(id = id, env = figure_env(meta)$name, source = source, version = version, license = license,
             data = paste(urls[nzchar(urls)], collapse = " "), stringsAsFactors = FALSE)
})
tab <- do.call(rbind, rows)
if (anyNA(tab$license)) stop("no license found for: ", paste(tab$id[is.na(tab$license)], collapse = ", "))

esc <- function(x) gsub("|", "\\|", x, fixed = TRUE)
out <- c(
  "# Sources of the frozen figures",
  "",
  "Generated by `bench/R/attribution.R`; do not edit by hand.",
  "",
  "Each directory holds `code.R` (the source's code up to the chosen figure, cleaned as recorded in its header and `meta.json`) and `meta.json`. The code is redistributed under its source's license, listed below: R Graph Gallery posts under the MIT License (`LICENSE-R-graph-gallery.txt`), package examples and vignettes under their package's license.",
  "",
  "Chapters of the ggtree book (the tree stratum, bench v1) are redistributed under the license of the book's online version, CC BY-NC-SA 4.0: with attribution, not for commercial use, and under the same license for what is derived from them.",
  "",
  "Data vendored from URLs at harvest time (`data/`) is **not** in git: several sources state no license. Its checksums are in `bench/MANIFEST.md5` and its URLs in each `meta.json` (`rewrites`).",
  "",
  "| Figure | Env | Source | Version | License | Vendored data (not in git) |",
  "|---|---|---|---|---|---|",
  sprintf("| %s | %s | %s | %s | %s | %s |", tab$id, tab$env, esc(tab$source), tab$version, esc(tab$license),
          ifelse(nzchar(tab$data), gsub(" ", "<br>", tab$data), "")))
writeLines(out, file.path(figures_root, "SOURCES.md"))
cat("attribution:", nrow(tab), "figures;", sum(nzchar(tab$data)), "with vendored data;",
    length(unique(tab$license)), "distinct licenses\n")
print(sort(table(tab$license), decreasing = TRUE))
